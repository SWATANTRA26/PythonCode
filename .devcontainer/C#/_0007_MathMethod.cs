using System;
class _0007_MathMethod
{
    public static void Main()
    {
        int number1 = 56;
        int number2 = 78;
        Console.WriteLine(Math.Max(number1, number2));  // Math.Max() is a stored method that returns the maximum of two numbers
        Console.WriteLine(Math.Min(number1, number2));  // Math.Min() is a stored method that returns the minimum of two numbers
        Console.WriteLine(Math.Sqrt(64));  // Math.Sqrt() is a stored method that returns the square root of a number
        Console.WriteLine(Math.Pow(2, 4));  // Math.Pow() is a stored method that returns the result of raising a number to a power
        Console.WriteLine(Math.Abs(-5));  // Math.Abs() is a stored method that returns the absolute value of a number
        Console.WriteLine(Math.Round(3.14159, 2));  // Math.Round() is a stored method that rounds a number to a specified number of decimal places 

    }
}